/// Look up an element by its symbol. The comparison is case sensitive, so
/// `"C"` finds carbon while `"c"` finds nothing.
pub fn by_symbol(symbol: &str) -> Option<&'static Element> {
    ELEMENTS.iter().find(|element| element.symbol == symbol)
}

/// Look up an element by atomic number Z, for Z in `1..=92`.
pub fn by_number(number: u8) -> Option<&'static Element> {
    ELEMENTS.get(usize::from(number.checked_sub(1)?))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn table_is_ordered_and_complete() {
        assert_eq!(ELEMENTS.len(), 92);
        for (index, element) in ELEMENTS.iter().enumerate() {
            assert_eq!(element.number as usize, index + 1);
        }
        for z in 1..=92u8 {
            assert_eq!(by_number(z).map(|element| element.number), Some(z));
        }
        assert_eq!(by_number(0), None);
        assert_eq!(by_number(93), None);
    }

    #[test]
    fn symbol_lookup_is_case_sensitive() {
        assert_eq!(by_symbol("C").map(|element| element.number), Some(6));
        assert_eq!(by_symbol("Cl").map(|element| element.number), Some(17));
        assert_eq!(by_symbol("c"), None);
        assert_eq!(by_symbol("CL"), None);
        assert_eq!(by_symbol(""), None);
    }

    #[test]
    fn carbon_twelve_is_exact() {
        assert_eq!(by_symbol("C").unwrap().mono_micro, 12_000_000);
    }

    #[test]
    fn every_entry_has_data() {
        for element in ELEMENTS {
            assert_ne!(element.weight_micro, 0, "{} weight", element.symbol);
            assert_ne!(element.mono_micro, 0, "{} monoisotopic", element.symbol);
            assert_ne!(element.covalent_pm, 0, "{} covalent", element.symbol);
            assert_ne!(element.vdw_pm, 0, "{} vdw", element.symbol);
            assert!(!element.symbol.is_empty());
            assert!(!element.name.is_empty());
        }
    }

    #[test]
    fn symbols_are_unique() {
        let mut seen = HashSet::new();
        for element in ELEMENTS {
            assert!(seen.insert(element.symbol), "duplicate {}", element.symbol);
        }
        assert_eq!(seen.len(), ELEMENTS.len());
    }

    #[test]
    fn masses_are_mutually_consistent() {
        for element in ELEMENTS {
            let weight = u64::from(element.weight_micro);
            let difference = weight.abs_diff(element.mono_micro);
            assert!(
                difference < 3_500_000,
                "{} weight and monoisotopic mass disagree",
                element.symbol
            );
        }
    }

    #[test]
    fn organic_valences_are_set() {
        for (symbol, valence) in [
            ("H", 1u8),
            ("B", 3),
            ("C", 4),
            ("N", 3),
            ("O", 2),
            ("F", 1),
            ("Si", 4),
            ("P", 3),
            ("S", 2),
            ("Cl", 1),
            ("Br", 1),
            ("I", 1),
            ("Se", 2),
        ] {
            assert_eq!(by_symbol(symbol).unwrap().valence, valence, "{symbol}");
        }
    }
}
