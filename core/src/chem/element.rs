/// A single chemical element and the physical constants needed to build,
/// weigh and draw a molecule containing it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Element {
    /// Atomic number Z.
    pub number: u8,
    /// Element symbol, case sensitive: `"C"`, `"Cl"`.
    pub symbol: &'static str,
    /// English element name.
    pub name: &'static str,
    /// Standard atomic weight in micro-unified-atomic-mass-units (u x 1e6).
    pub weight_micro: u32,
    /// Monoisotopic mass in micro-unified-atomic-mass-units (u x 1e6).
    pub mono_micro: u64,
    /// Single-bond covalent radius in picometres.
    pub covalent_pm: u16,
    /// Van der Waals radius in picometres.
    pub vdw_pm: u16,
    /// CPK/Jmol display colour as `[r, g, b]`.
    pub colour: [u8; 3],
    /// Usual number of covalent bonds in a neutral organic molecule; 0 where
    /// the notion does not apply.
    pub valence: u8,
}

